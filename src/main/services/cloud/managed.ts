import log from "electron-log/main";
import type { ManagedRequest } from "@shared/cloud/licensing";

/** A presence marker only, never a credential. All provider requests use the cloud gateway. */
export const MANAGED = "kairo-managed";
/** Injectable boundary keeps provider algorithms testable without a cloud session. */
export const managedTransport = {
  async request<T>(request: ManagedRequest): Promise<T> {
    const { licensing } = await import("./licensing");
    return licensing.request<T>(request);
  },
};
export async function managedJson<T>(
  provider: ManagedRequest["provider"],
  path: string,
  body?: unknown,
  query?: ManagedRequest["query"],
  purpose: ManagedRequest["purpose"] = "scripture",
): Promise<T> {
  return managedTransport.request<T>(
    managedPayload(provider, path, body, query, purpose),
  );
}

/** Dedicated endpoints use their intrinsic feature; only LLM requests carry a purpose. */
export function managedPayload(
  provider: ManagedRequest["provider"],
  path: string,
  body?: unknown,
  query?: ManagedRequest["query"],
  purpose: ManagedRequest["purpose"] = "scripture",
): ManagedRequest {
  return {
    provider,
    path,
    method: body === undefined ? "GET" : "POST",
    ...(body === undefined ? {} : { body }),
    ...(query ? { query } : {}),
    ...(["anthropic", "deepseek"].includes(provider) ? { purpose } : {}),
  };
}

/** SDK fetch adapter. Credentials generated by SDKs never leave the process. */
export function managedFetch(
  provider: "anthropic" | "deepseek",
  purpose: ManagedRequest["purpose"] = "scripture",
): typeof fetch {
  return async (input, init) => {
    const url = new URL(
      typeof input === "string"
        ? input
        : input instanceof URL
          ? input.href
          : input.url,
    );
    const signal =
      init?.signal ?? (input instanceof Request ? input.signal : undefined);
    const abortError = (): unknown =>
      signal?.reason ?? new DOMException("Request aborted", "AbortError");
    if (signal?.aborted) throw abortError();
    const text =
      typeof init?.body === "string"
        ? init.body
        : input instanceof Request
          ? await input.clone().text()
          : "";
    const body = text ? JSON.parse(text) : undefined;
    // The gateway returns JSON; streaming is never passed to provider APIs.
    if (body && typeof body === "object") delete body.stream;
    const request = managedJson(
      provider,
      url.pathname,
      body,
      undefined,
      purpose,
    );
    let data: unknown;
    try {
      data = signal
        ? await new Promise<unknown>((resolve, reject) => {
            const abort = (): void => reject(abortError());
            signal.addEventListener("abort", abort, { once: true });
            if (signal.aborted) abort();
            request
              .then(resolve, reject)
              .finally(() => signal.removeEventListener("abort", abort));
          })
        : await request;
    } catch (error) {
      if (signal?.aborted) throw error;
      // Thrown, this became the SDK's bare "Connection error." and hid why —
      // not activated, minutes used up, Kairo unreachable. As an HTTP error
      // response the SDK reports the server's own words.
      const { status, message } = error as { status?: unknown; message?: unknown };
      const reason = typeof message === "string" && message ? message : "Kairo could not complete the request";
      const code = typeof status === "number" && status >= 400 ? status : 503;
      log.warn("[Managed] AI request failed", { provider, status: code, reason });
      return new Response(JSON.stringify({ type: "error", message: reason, error: { type: "api_error", message: reason } }), {
        status: code,
        headers: { "Content-Type": "application/json" },
      });
    }
    return new Response(JSON.stringify(data), {
      status: 200,
      headers: { "Content-Type": "application/json" },
    });
  };
}
