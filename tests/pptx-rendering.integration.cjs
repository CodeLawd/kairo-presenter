// Optional local deck regression: electron tests/pptx-rendering.integration.cjs /path/to/deck.pptx
const {app, BrowserWindow}=require('electron')
const {buildSync}=require('esbuild')
const fs=require('node:fs/promises')
const path=require('node:path')
const os=require('node:os')
const assert=require('node:assert/strict')
app.on('window-all-closed',()=>{})
app.whenReady().then(async()=>{
 const dir=await fs.mkdtemp(path.join(os.tmpdir(),'kairo-pptx-render-'))
 app.setPath('userData',dir)
 buildSync({entryPoints:['src/main/services/documents/pptx-builtin.ts'],outfile:path.join(dir,'converter.cjs'),bundle:true,platform:'node',external:['electron'],alias:{'@shared':path.resolve('src/lib')}})
 await require(path.join(dir,'converter.cjs')).convertPptxBuiltin(process.argv[2],path.join(dir,'deck.pdf'),dir)
 const win=new BrowserWindow({show:false,width:1920,height:1080,webPreferences:{sandbox:true,contextIsolation:true,nodeIntegration:false}})
 await win.loadFile(path.join(dir,'slides.html'))
 const result=await win.webContents.executeJavaScript(`({pages:document.querySelectorAll('.slide').length,background:getComputedStyle(document.querySelector('.slide')).backgroundColor,text:document.body.innerText})`)
 assert.equal(result.pages,13)
 assert.equal(result.background,'rgb(22, 22, 22)')
 assert.match(result.text,/Frontend architecture/)
 assert.equal(await win.webContents.executeJavaScript('[...document.images].every(img=>img.complete && img.naturalWidth>0)'),true)
 await win.webContents.executeJavaScript('document.querySelectorAll(".slide")[8].scrollIntoView()')
 await new Promise(resolve=>setTimeout(resolve,150))
 await fs.writeFile('/tmp/kairo-betpikr-video-poster.png',(await win.webContents.capturePage()).toPNG())
 await fs.writeFile('/tmp/kairo-betpikr-slide1.png',(await win.webContents.capturePage()).toPNG())
 console.log(JSON.stringify({dir,...result}))
 win.destroy();app.quit()
}).catch(e=>{console.error(e);app.exit(1)})
